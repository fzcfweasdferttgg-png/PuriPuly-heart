"""Official audio-model list from the unified model catalog.

The upstream transcribe.cpp digest is stored under ``official_catalog`` in
``data/models/catalog.json`` and regenerated by the catalog build script.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache

from puripuly_heart.runtime_layout import current_runtime_layout

_DIGEST_RELATIVE = ("data", "models", "catalog.json")
_PREFERRED_QUANTS = ("Q6_K", "Q8_0", "Q5_K_M", "Q4_K_M", "F16", "BF16")


@dataclass(frozen=True, slots=True)
class CatalogDownload:
    quant: str
    filename: str
    size_bytes: int


@dataclass(frozen=True, slots=True)
class CatalogModel:
    model_id: str
    family: str
    role: str
    name: str
    params: int
    license: str
    languages: tuple[str, ...]
    repo: str
    capabilities: tuple[str, ...]
    downloads: tuple[CatalogDownload, ...]
    accuracy: dict[str, dict[str, dict]]

    def download(self, quant: str) -> CatalogDownload | None:
        for item in self.downloads:
            if item.quant == quant:
                return item
        return None

    def accuracy_for(self, language: str | None, quant: str | None) -> str:
        """Formatted accuracy cell for one language (falls back across quants)."""
        if not language:
            language = "ru" if "ru" in self.accuracy else next(iter(self.accuracy), None)
            if not language:
                return ""
        quants = self.accuracy.get(language) or {}
        if not quants:
            return ""
        cell = None
        if quant and quant in quants:
            cell = quants[quant]
        else:
            for preferred in _PREFERRED_QUANTS:
                if preferred in quants:
                    cell = quants[preferred]
                    break
            if cell is None:
                cell = next(iter(quants.values()))
        metric = str(cell.get("metric") or "wer")
        if metric == "accuracy":
            value = cell.get("acc_pct")
            return f"Acc {value:.1f}%" if isinstance(value, (int, float)) else ""
        value = cell.get("err_pct")
        if not isinstance(value, (int, float)):
            return ""
        return f"{metric.upper()} {value:.1f}%"

    @property
    def params_label(self) -> str:
        if self.params >= 1_000_000_000:
            return f"{self.params / 1_000_000_000:.1f}B"
        if self.params >= 1_000_000:
            return f"{self.params / 1_000_000:.0f}M"
        return f"{self.params / 1000:.0f}K" if self.params else ""


@lru_cache(maxsize=1)
def load_transcribe_catalog() -> tuple[CatalogModel, ...]:
    path = current_runtime_layout().package_resource(*_DIGEST_RELATIVE)
    payload = json.loads(path.read_text(encoding="utf-8"))
    payload = payload.get("official_catalog", payload)
    models: list[CatalogModel] = []
    for item in payload.get("models") or ():
        models.append(
            CatalogModel(
                model_id=str(item["id"]),
                family=str(item.get("family") or ""),
                role=str(item.get("role") or "asr"),
                name=str(item.get("name") or item["id"]),
                params=int(item.get("params") or 0),
                license=str(item.get("license") or ""),
                languages=tuple(item.get("languages") or ()),
                repo=str(item["repo"]),
                capabilities=tuple(item.get("capabilities") or ()),
                downloads=tuple(
                    CatalogDownload(
                        quant=str(download["quant"]),
                        filename=str(download["filename"]),
                        size_bytes=int(download["size_bytes"]),
                    )
                    for download in item.get("downloads") or ()
                ),
                accuracy={
                    str(language): dict(quants)
                    for language, quants in (item.get("accuracy") or {}).items()
                },
            )
        )
    return tuple(models)


__all__ = [
    "CatalogDownload",
    "CatalogModel",
    "load_transcribe_catalog",
]
